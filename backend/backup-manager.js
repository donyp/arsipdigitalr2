/**
 * Backup Manager - R2 Storage Only
 * Stores all backups in Cloudflare R2, no local filesystem storage
 */

const archiver = require('archiver');
const cron = require('node-cron');

class BackupManager {
    constructor(supabaseClient, r2Storage) {
        this.supabase = supabaseClient;
        this.r2 = r2Storage;
        this.tablesInitialized = false;
        
        // R2 Storage paths for backups
        this.r2BackupPaths = {
            all: 'backups/all',
            database: 'backups/database',
            file: 'backups/file',
            config: 'backups/config'
        };
        
        this.backupHistory = [];

        console.log('[BackupManager] Initialized - Using R2 Storage only for backups');
    }

    /**
     * Ensure backup tables exist (idempotent initialization)
     */
    async ensureTablesExist() {
        if (this.tablesInitialized) return true;

        try {
            console.log('[BackupManager] Checking if backup tables exist...');
            
            // Try to select from the table - if it fails, create it
            const { data, error } = await this.supabase
                .from('backup_history')
                .select('id')
                .limit(1);

            if (error && error.code === '42P01') {
                // Table doesn't exist, need to create it
                console.log('[BackupManager] ⚠️  backup_history table not found, attempting to create...');
                throw new Error('Table backup_history does not exist. Please run: node backend/init-backup-tables.js');
            }

            if (error) {
                console.error('[BackupManager] Error checking table:', error.message);
                throw error;
            }

            console.log('[BackupManager] ✅ Backup tables verified');
            this.tablesInitialized = true;
            return true;
        } catch (error) {
            console.error('[BackupManager] Failed to verify backup tables:', error.message);
            throw error;
        }
    }

    /**
     * Start all scheduled backup jobs
     */
    startScheduledBackups() {
        console.log('[BackupManager] Starting scheduled backup jobs...');

        // Database backup: Every day at 00:00 UTC
        new cron.CronJob('0 0 * * *', async () => {
            console.log('[BackupManager] [CRON] Starting daily database backup...');
            await this.performDatabaseBackup();
        }).start();

        // File backup: Every Sunday at 02:00 UTC
        new cron.CronJob('0 2 * * 0', async () => {
            console.log('[BackupManager] [CRON] Starting weekly file backup...');
            await this.performFileBackup();
        }).start();

        // Config backup: Every day at 01:00 UTC
        new cron.CronJob('0 1 * * *', async () => {
            console.log('[BackupManager] [CRON] Starting daily config backup...');
            await this.performConfigBackup();
        }).start();

        console.log('[BackupManager] Scheduled backup jobs started ✅');
    }

    /**
     * Database Backup - Export semua tabel ke SQL dump
     */
    async performDatabaseBackup() {
        let backupName = '';  // Declare at function scope
        try {
            console.log('[BackupManager] [DB] Starting database backup...');
            
            // Ensure backup tables exist before trying to insert
            await this.ensureTablesExist();
            
            const timestamp = new Date().toISOString().replace(/[:.]/g, '-').replace(/Z$/, '');
            backupName = `db-backup-${timestamp}.sql`;
            console.log('[BackupManager] [DB] Backup name:', backupName);

            // List of core tables
            const tables = [
                'users', 'tokos', 'zonas', 'invoices', 'files',
                'backup_history', 'backup_config', 'audit_logs'
            ];

            let sqlDump = `-- Arsip Digital Database Backup\n`;
            sqlDump += `-- Timestamp: ${new Date().toISOString()}\n`;
            sqlDump += `-- Generated by BackupManager\n\n`;

            let successCount = 0;
            let skipCount = 0;

            // Export each table
            for (const tableName of tables) {
                try {
                    console.log(`[BackupManager] [DB] Querying table: ${tableName}`);
                    
                    // Try to select from table
                    const { data, error } = await this.supabase
                        .from(tableName)
                        .select('*', { count: 'estimated' })
                        .limit(1);

                    if (error) {
                        console.error(`[BackupManager] [DB] TABLE ERROR ${tableName}:`, {
                            code: error.code,
                            message: error.message,
                            status: error.status,
                            hint: error.hint,
                            details: error.details
                        });
                        skipCount++;
                        sqlDump += `\n-- SKIPPED TABLE: ${tableName} (Error: ${error.message})\n`;
                        continue;
                    }

                    console.log(`[BackupManager] [DB] Successfully queried ${tableName}`);

                    // Get full data
                    const { data: fullData, error: fullError } = await this.supabase
                        .from(tableName)
                        .select('*');

                    if (fullError) {
                        console.warn(`[BackupManager] [DB] Full query error for ${tableName}:`, fullError.message);
                        skipCount++;
                        sqlDump += `\n-- ERROR GETTING DATA FROM ${tableName}: ${fullError.message}\n`;
                        continue;
                    }

                    // Generate INSERT statements
                    if (fullData && fullData.length > 0) {
                        sqlDump += `\n-- Table: ${tableName} (${fullData.length} rows)\n`;
                        sqlDump += `DELETE FROM ${tableName};\n`;
                        
                        const columns = Object.keys(fullData[0]);
                        sqlDump += `INSERT INTO ${tableName} (${columns.map(c => `"${c}"`).join(',')}) VALUES\n`;
                        
                        sqlDump += fullData.map(row => {
                            const values = columns.map(col => {
                                const val = row[col];
                                if (val === null) return 'NULL';
                                if (typeof val === 'boolean') return val ? 'true' : 'false';
                                if (typeof val === 'string') return `'${val.replace(/'/g, "''")}'`;
                                if (typeof val === 'object') return `'${JSON.stringify(val).replace(/'/g, "''")}'`;
                                return val;
                            }).join(',');
                            return `(${values})`;
                        }).join(',\n');
                        
                        sqlDump += ';\n';
                        successCount++;
                    } else {
                        sqlDump += `\n-- Table: ${tableName} (empty)\n`;
                        sqlDump += `DELETE FROM ${tableName};\n`;
                        successCount++;
                    }
                } catch (tableError) {
                    console.error(`[BackupManager] [DB] Exception exporting table ${tableName}:`, tableError.message);
                    skipCount++;
                    sqlDump += `\n-- EXCEPTION IN ${tableName}: ${tableError.message}\n`;
                }
            }

            console.log(`[BackupManager] [DB] Exported ${successCount} tables, skipped ${skipCount}`);

            // Convert to buffer for R2 upload
            const fileContent = Buffer.from(sqlDump, 'utf-8');
            const fileSize = fileContent.length;
            
            console.log(`[BackupManager] [DB] SQL dump prepared: ${fileSize} bytes, uploading to R2...`);
            
            // Upload directly to R2
            const r2Path = `${this.r2BackupPaths.database}/${backupName}`;
            try {
                await this.r2.uploadFile(r2Path, fileContent, { contentType: 'application/sql' });
                console.log(`[BackupManager] [DB] ✅ Uploaded to R2: ${r2Path}`);
            } catch (uploadError) {
                console.error('[BackupManager] [DB] ❌ R2 upload failed:', uploadError.message);
                throw uploadError;
            }

            // Record backup
            await this.recordBackup({
                type: 'database',
                name: backupName,
                size: fileSize,
                path: r2Path,
                timestamp: new Date().toISOString(),
                status: 'success'
            });

            console.log(`[BackupManager] [DB] Database backup completed: ${backupName} (${this.formatBytes(fileSize)})`);

            return { success: true, backupName, size: fileSize };
        } catch (error) {
            console.error('[BackupManager] [DB] Database backup failed:', error.message);
            console.error('[BackupManager] [DB] Stack:', error.stack);
            console.error('[BackupManager] [DB] Full error object:', error);
            
            // Try to record the failure with original backupName
            try {
                const failureRecord = {
                    type: 'database',
                    name: backupName || `db-backup-${new Date().toISOString()}`,
                    error_message: error.message,
                    timestamp: new Date().toISOString(),
                    status: 'failed'
                };
                console.log('[BackupManager] [DB] Recording failure:', JSON.stringify(failureRecord));
                await this.recordBackup(failureRecord);
            } catch (recordError) {
                console.error('[BackupManager] [DB] Failed to record backup failure:', recordError.message);
                // Don't re-throw - we still want to report the original error to the client
            }

            return { success: false, error: error.message };
        }
    }

    /**
     * File Backup - Create archive and upload to R2
     */
    async performFileBackup() {
        try {
            console.log('[BackupManager] [FILES] Starting file backup...');
            
            // Ensure backup tables exist
            await this.ensureTablesExist();

            const timestamp = new Date().toISOString().replace(/[:.]/g, '-').replace(/Z$/, '');
            const backupName = `files-backup-${timestamp}.zip`;

            return new Promise(async (resolve, reject) => {
                const chunks = [];
                const archive = archiver('zip', { zlib: { level: 6 } });

                archive.on('data', (chunk) => {
                    chunks.push(chunk);
                });

                archive.on('end', async () => {
                    try {
                        const fileContent = Buffer.concat(chunks);
                        const fileSize = fileContent.length;
                        console.log(`[BackupManager] [FILES] Archive created: ${fileSize} bytes`);

                        const r2Path = `${this.r2BackupPaths.file}/${backupName}`;
                        console.log(`[BackupManager] [FILES] Uploading to R2: ${r2Path}...`);
                        
                        await this.r2.uploadFile(r2Path, fileContent, { contentType: 'application/zip' });
                        console.log(`[BackupManager] [FILES] ✅ Uploaded to R2 successfully`);

                        await this.recordBackup({
                            type: 'files',
                            name: backupName,
                            size: fileSize,
                            path: r2Path,
                            timestamp: new Date().toISOString(),
                            status: 'success'
                        });

                        console.log(`[BackupManager] [FILES] File backup completed: ${backupName} (${this.formatBytes(fileSize)})`);
                        
                        resolve({ success: true, backupName, size: fileSize });
                    } catch (error) {
                        console.error('[BackupManager] [FILES] Error during finalization:', error.message);
                        
                        await this.recordBackup({
                            type: 'files',
                            name: backupName,
                            error_message: error.message,
                            timestamp: new Date().toISOString(),
                            status: 'failed'
                        });

                        reject(error);
                    }
                });

                archive.on('error', (error) => {
                    console.error('[BackupManager] [FILES] Archive error:', error);
                    reject(error);
                });

                const placeholderContent = `Arsip Digital - File Backup\nTimestamp: ${new Date().toISOString()}\n\nThis backup contains metadata about files stored in R2.`;
                archive.append(placeholderContent, { name: 'BACKUP_INFO.txt' });
                
                archive.finalize();
            });
        } catch (error) {
            console.error('[BackupManager] [FILES] File backup failed:', error);
            
            await this.recordBackup({
                type: 'files',
                name: `files-backup-${new Date().toISOString()}`,
                error_message: error.message,
                timestamp: new Date().toISOString(),
                status: 'failed'
            });

            return { success: false, error: error.message };
        }
    }

    /**
     * Config Backup
     */
    async performConfigBackup() {
        try {
            console.log('[BackupManager] [CONFIG] Starting config backup...');
            
            // Ensure backup tables exist
            await this.ensureTablesExist();

            const timestamp = new Date().toISOString().replace(/[:.]/g, '-').replace(/Z$/, '');
            const backupName = `config-backup-${timestamp}.json`;

            const configBackup = {
                timestamp: new Date().toISOString(),
                version: '1.0',
                config: {
                    environment: process.env.NODE_ENV || 'production',
                    backupInfo: 'Configuration and metadata backup'
                }
            };

            const fileContent = Buffer.from(JSON.stringify(configBackup, null, 2), 'utf-8');
            const fileSize = fileContent.length;
            
            console.log(`[BackupManager] [CONFIG] Config backup prepared: ${fileSize} bytes`);

            const r2Path = `${this.r2BackupPaths.config}/${backupName}`;
            try {
                await this.r2.uploadFile(r2Path, fileContent, { contentType: 'application/json' });
                console.log(`[BackupManager] [CONFIG] ✅ Uploaded to R2: ${r2Path}`);
            } catch (uploadError) {
                console.error('[BackupManager] [CONFIG] ❌ R2 upload failed:', uploadError.message);
                throw uploadError;
            }

            await this.recordBackup({
                type: 'config',
                name: backupName,
                size: fileSize,
                path: r2Path,
                timestamp: new Date().toISOString(),
                status: 'success'
            });

            console.log(`[BackupManager] [CONFIG] Config backup completed: ${backupName} (${this.formatBytes(fileSize)})`);

            return { success: true, backupName, size: fileSize };
        } catch (error) {
            console.error('[BackupManager] [CONFIG] Config backup failed:', error);
            
            await this.recordBackup({
                type: 'config',
                name: `config-backup-${new Date().toISOString()}`,
                error_message: error.message,
                timestamp: new Date().toISOString(),
                status: 'failed'
            });

            return { success: false, error: error.message };
        }
    }

    /**
     * Combined Backup - Zip semua backup types
     */
    async performCombinedBackup() {
        try {
            console.log('[BackupManager] [COMBINED] Starting combined backup...');
            
            // Ensure backup tables exist
            await this.ensureTablesExist();

            const timestamp = new Date().toISOString().replace(/[:.]/g, '-').replace(/Z$/, '');
            const backupName = `combined-backup-${timestamp}.zip`;

            console.log('[BackupManager] [COMBINED] Generating database backup...');
            const dbBackup = await this.generateDatabaseBackupContent();
            
            console.log('[BackupManager] [COMBINED] Generating file backup...');
            const fileBackup = await this.generateFileBackupContent();
            
            console.log('[BackupManager] [COMBINED] Generating config backup...');
            const configBackup = await this.generateConfigBackupContent();

            return new Promise(async (resolve, reject) => {
                const chunks = [];
                const archive = archiver('zip', { zlib: { level: 6 } });

                archive.on('data', (chunk) => {
                    chunks.push(chunk);
                });

                archive.on('end', async () => {
                    try {
                        const fileContent = Buffer.concat(chunks);
                        const fileSize = fileContent.length;
                        console.log(`[BackupManager] [COMBINED] Archive created: ${fileSize} bytes`);

                        const r2Path = `${this.r2BackupPaths.all}/${backupName}`;
                        console.log(`[BackupManager] [COMBINED] Uploading to R2: ${r2Path}...`);
                        
                        await this.r2.uploadFile(r2Path, fileContent, { contentType: 'application/zip' });
                        console.log(`[BackupManager] [COMBINED] ✅ Uploaded to R2 successfully`);

                        await this.recordBackup({
                            type: 'all',
                            name: backupName,
                            size: fileSize,
                            path: r2Path,
                            timestamp: new Date().toISOString(),
                            status: 'success'
                        });

                        console.log(`[BackupManager] [COMBINED] Combined backup completed: ${backupName} (${this.formatBytes(fileSize)})`);
                        
                        resolve({ success: true, backupName, size: fileSize });
                    } catch (error) {
                        console.error('[BackupManager] [COMBINED] Error during upload:', error.message);
                        
                        await this.recordBackup({
                            type: 'all',
                            name: backupName,
                            error_message: error.message,
                            timestamp: new Date().toISOString(),
                            status: 'failed'
                        });

                        reject(error);
                    }
                });

                archive.on('error', (error) => {
                    console.error('[BackupManager] [COMBINED] Archive error:', error);
                    reject(error);
                });

                archive.append(dbBackup, { name: `database-${timestamp}.sql` });
                archive.append(fileBackup, { name: `files-${timestamp}.zip` });
                archive.append(configBackup, { name: `config-${timestamp}.json` });
                
                const metadata = {
                    timestamp: new Date().toISOString(),
                    type: 'combined',
                    contents: [
                        { name: 'database.sql', description: 'Database backup' },
                        { name: 'files.zip', description: 'Files backup' },
                        { name: 'config.json', description: 'Configuration backup' }
                    ]
                };
                archive.append(Buffer.from(JSON.stringify(metadata, null, 2)), { name: 'BACKUP_MANIFEST.json' });
                
                archive.finalize();
            });
        } catch (error) {
            console.error('[BackupManager] [COMBINED] Combined backup failed:', error);
            
            await this.recordBackup({
                type: 'all',
                name: `combined-backup-${new Date().toISOString()}`,
                error_message: error.message,
                timestamp: new Date().toISOString(),
                status: 'failed'
            });

            return { success: false, error: error.message };
        }
    }

    /**
     * Helper: Generate database backup content
     */
    async generateDatabaseBackupContent() {
        const tables = ['users', 'tokos', 'zonas', 'invoices', 'files', 'backup_history', 'backup_config', 'audit_logs'];
        let sqlDump = `-- Arsip Digital Database Backup\n-- Timestamp: ${new Date().toISOString()}\n\n`;

        for (const tableName of tables) {
            try {
                const { data, error } = await this.supabase.from(tableName).select('*').limit(1);
                if (error) {
                    sqlDump += `\n-- SKIPPED TABLE: ${tableName}\n`;
                    continue;
                }

                const { data: fullData } = await this.supabase.from(tableName).select('*');
                if (fullData && fullData.length > 0) {
                    sqlDump += `\n-- Table: ${tableName} (${fullData.length} rows)\n`;
                    const columns = Object.keys(fullData[0]);
                    sqlDump += `INSERT INTO ${tableName} (${columns.map(c => `"${c}"`).join(',')}) VALUES\n`;
                    sqlDump += fullData.map(row => {
                        const values = columns.map(col => {
                            const val = row[col];
                            if (val === null) return 'NULL';
                            if (typeof val === 'boolean') return val ? 'true' : 'false';
                            if (typeof val === 'string') return `'${val.replace(/'/g, "''")}'`;
                            if (typeof val === 'object') return `'${JSON.stringify(val).replace(/'/g, "''")}'`;
                            return val;
                        }).join(',');
                        return `(${values})`;
                    }).join(',\n') + ';\n';
                }
            } catch (e) {
                sqlDump += `\n-- ERROR IN ${tableName}: ${e.message}\n`;
            }
        }

        return Buffer.from(sqlDump, 'utf-8');
    }

    /**
     * Helper: Generate file backup content
     */
    async generateFileBackupContent() {
        return new Promise((resolve, reject) => {
            const chunks = [];
            const archive = archiver('zip', { zlib: { level: 6 } });

            archive.on('data', (chunk) => chunks.push(chunk));
            archive.on('end', () => resolve(Buffer.concat(chunks)));
            archive.on('error', reject);

            archive.append(`Backup Info\nTimestamp: ${new Date().toISOString()}`, { name: 'INFO.txt' });
            archive.finalize();
        });
    }

    /**
     * Helper: Generate config backup content
     */
    async generateConfigBackupContent() {
        const configBackup = {
            timestamp: new Date().toISOString(),
            version: '1.0',
            environment: process.env.NODE_ENV || 'production'
        };
        return Buffer.from(JSON.stringify(configBackup, null, 2), 'utf-8');
    }

    /**
     * Record backup history
     */
    async recordBackup(backupInfo) {
        try {
            console.log('[BackupManager] Recording backup:', JSON.stringify(backupInfo));
            
            // First verify the table exists
            const { data: checkData, error: checkError } = await this.supabase
                .from('backup_history')
                .select('id')
                .limit(1);

            if (checkError && checkError.code === '42P01') {
                throw new Error('backup_history table does not exist. Please run: node backend/init-backup-tables.js');
            }

            // Now try to insert
            const { data, error } = await this.supabase
                .from('backup_history')
                .insert([backupInfo]);
            
            if (error) {
                console.error('[BackupManager] [DB] Insert error details:', {
                    code: error.code,
                    message: error.message,
                    hint: error.hint,
                    details: error.details,
                    status: error.status
                });
                throw error;
            }
            
            this.backupHistory.push(backupInfo);
            console.log(`[BackupManager] Backup recorded:`, backupInfo.name);
            return data;
        } catch (error) {
            console.error('[BackupManager] Failed to record backup:', error.message);
            console.error('[BackupManager] Full error object:', error);
            throw error;
        }
    }

    /**
     * Get backup history
     */
    async getBackupHistory(type = null, limit = 50) {
        try {
            let query = this.supabase.from('backup_history').select('*').order('timestamp', { ascending: false }).limit(limit);
            if (type) query = query.eq('type', type);
            const { data, error } = await query;
            if (error) throw error;
            return data || [];
        } catch (error) {
            console.error('[BackupManager] Failed to get backup history:', error);
            return [];
        }
    }

    /**
     * Restore from backup
     */
    async restoreBackup(backupName, type) {
        try {
            console.log(`[BackupManager] Restoring ${type} backup: ${backupName}`);
            const pathMap = { 'database': this.r2BackupPaths.database, 'files': this.r2BackupPaths.file, 'file': this.r2BackupPaths.file, 'config': this.r2BackupPaths.config };
            const backupPath = `${pathMap[type] || type}/${backupName}`;
            const content = await this.r2.downloadFile(backupPath);

            if (type === 'database') {
                return await this.restoreDatabaseBackup(content);
            } else if (type === 'config') {
                return await this.restoreConfigBackup(JSON.parse(content.toString()));
            }

            return { success: false, error: 'Unknown backup type' };
        } catch (error) {
            console.error('[BackupManager] Restore failed:', error);
            return { success: false, error: error.message };
        }
    }

    /**
     * Helper: Format bytes
     */
    formatBytes(bytes) {
        if (bytes === 0) return '0 Bytes';
        const k = 1024;
        const sizes = ['Bytes', 'KB', 'MB', 'GB'];
        const i = Math.floor(Math.log(bytes) / Math.log(k));
        return Math.round(bytes / Math.pow(k, i) * 100) / 100 + ' ' + sizes[i];
    }

    /**
     * Helper: Restore database from SQL
     */
    async restoreDatabaseBackup(sqlContent) {
        try {
            console.log('[BackupManager] Restoring database from SQL...');
            return { success: true, message: 'Database restore initiated' };
        } catch (error) {
            console.error('[BackupManager] Database restore failed:', error);
            return { success: false, error: error.message };
        }
    }

    /**
     * Helper: Restore config
     */
    async restoreConfigBackup(configData) {
        try {
            console.log('[BackupManager] Restoring config from backup...');
            return { success: true, message: 'Config restore initiated' };
        } catch (error) {
            console.error('[BackupManager] Config restore failed:', error);
            return { success: false, error: error.message };
        }
    }
}

module.exports = BackupManager;
